// Builds the shared, template-versioned assets once: CSS, client bundle, template images.
// Output: dist/shared/<version>/... where <version> is a content hash, so the files can be
// cached forever. Per-site publishing only renders HTML that points at this version.
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { cpSync, mkdirSync, readFileSync, readdirSync, renameSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const staging = join(root, "dist/.staging");
const assets = join(staging, "_assets");
rmSync(join(root, "dist"), { recursive: true, force: true });
mkdirSync(assets, { recursive: true });

execFileSync(
  join(root, "node_modules/.bin/tailwindcss"),
  ["-i", "src/styles.css", "-o", join(assets, "site.css"), "--minify"],
  { cwd: root, stdio: ["ignore", "ignore", "inherit"] },
);

// Replace whole react-icons sets with the allowlist modules (src/icons/*.ts).
const iconSets = { "react-icons/fa6": "src/icons/fa6.ts", "react-icons/fi": "src/icons/fi.ts" };
const iconAllowlist = {
  name: "icon-allowlist",
  setup(b) {
    b.onResolve({ filter: /^react-icons\/(fa6|fi)$/ }, (args) => {
      const target = join(root, iconSets[args.path]);
      if (args.importer === target) return undefined; // the allowlist module itself imports the real set
      return { path: target };
    });
  },
};

await build({
  entryPoints: [join(root, "src/client.tsx")],
  outdir: assets,
  entryNames: "[name]",
  chunkNames: "chunks/[name]-[hash]",
  bundle: true,
  splitting: true,
  format: "esm",
  minify: true,
  target: "es2022",
  jsx: "automatic",
  define: { "process.env.NODE_ENV": '"production"' },
  plugins: [iconAllowlist],
  logLevel: "warning",
});

cpSync(join(root, "node_modules/@dani-builder/site-templates/assets/business-basic"), join(staging, "site-templates"), {
  recursive: true,
});

// Responsive WebP variants next to each sample photo (src/images.ts names them).
const { default: sharp } = await import("sharp");
const { VARIANT_WIDTHS, VARIANT_QUALITY, variantUrl } = await import("../src/images.ts");
for (const file of readdirSync(join(staging, "site-templates")).filter((f) => /\.(jpg|png)$/.test(f))) {
  const src = join(staging, "site-templates", file);
  const { width } = await sharp(src).metadata();
  for (const w of VARIANT_WIDTHS.filter((w) => w < width)) {
    await sharp(src).resize({ width: w }).webp({ quality: VARIANT_QUALITY }).toFile(variantUrl(src, w));
  }
}

function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? walk(join(dir, e.name)) : [join(dir, e.name)],
  );
}
const files = walk(staging).sort();
const hash = createHash("sha256");
for (const file of files) hash.update(relative(staging, file)).update(readFileSync(file));
const version = hash.digest("hex").slice(0, 12);

mkdirSync(join(root, "dist/shared"), { recursive: true });
renameSync(staging, join(root, "dist/shared", version));
mkdirSync(join(root, "src/generated"), { recursive: true });
writeFileSync(
  join(root, "src/generated/asset-version.ts"),
  `// Generated by scripts/build-assets.mjs. Do not edit.\nexport const ASSET_VERSION = "${version}";\n`,
);

const kib = (f) => (statSync(join(root, "dist/shared", version, f)).size / 1024).toFixed(1);
const chunkDir = join(root, "dist/shared", version, "_assets/chunks");
const chunkKiB = readdirSync(chunkDir).reduce((s, f) => s + statSync(join(chunkDir, f)).size, 0) / 1024;
console.log(`asset version ${version}: ${files.length} files`);
console.log(`site.css ${kib("_assets/site.css")} KiB, client.js ${kib("_assets/client.js")} KiB, chunks ${chunkKiB.toFixed(1)} KiB`);
